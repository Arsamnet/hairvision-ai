<?php

namespace App\Services;

use App\Models\Lead;
use App\Models\OtpCode;
use App\Services\Sms\SmsGatewayService;
use App\Support\DebugStepLogger;
use App\Support\NumberNormalizer;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Hash;
use Random\RandomException;
use Symfony\Component\HttpFoundation\Response;
use Throwable;

/**
 * Manages tenant-scoped visitor OTPs.
 *
 * @since 1.0.0
 */
class OtpService
{
    public function __construct(private readonly SmsGatewayService $smsGateways) {}

    /**
     * Create a hashed OTP record and send it by SMS.
     *
     * @throws RandomException
     */
    public function requestCode(string $phone, string $ipAddress, int $tenantId, ?Request $request = null): OtpCode
    {
        $scope = 'public.otp.service.request_code';

        $phoneNormalized = $this->normalizePhone($phone);
        $phoneHash = hash('sha256', $phoneNormalized);
        $ipHash = $ipAddress !== '' ? hash('sha256', $ipAddress) : null;

        $this->debugStep($request, $scope, 'Request received', [
            'tenant_id' => $tenantId,
            'phone_hash' => $phoneHash,
            'ip_hash' => $ipHash,
        ]);

        $expiresAt = Carbon::now()->addMinutes(2);

        try {
            $code = str_pad((string) random_int(100000, 999999), 6, '0', STR_PAD_LEFT);
        } catch (RandomException $exception) {
            $this->debugStep($request, $scope, 'OTP generation failed', [
                'tenant_id' => $tenantId,
                'phone_hash' => $phoneHash,
                'exception' => $exception::class,
            ]);

            throw $exception;
        }

        $this->debugStep($request, $scope, 'OTP generated', [
            'tenant_id' => $tenantId,
            'phone_hash' => $phoneHash,
            'code_length' => strlen($code),
            'expires_at' => $expiresAt->toISOString(),
        ]);

        try {
            $otp = OtpCode::create([
                'tenant_id' => $tenantId,
                'phone_normalized' => $phoneNormalized,
                'code_hash' => Hash::make($code),
                'purpose' => 'lead_login',
                'expires_at' => $expiresAt,
                'ip_address' => $ipAddress,
                'attempts' => 0,
            ]);
        } catch (Throwable $exception) {
            $this->debugStep($request, $scope, 'OTP record creation failed', [
                'tenant_id' => $tenantId,
                'phone_hash' => $phoneHash,
                'exception' => $exception::class,
            ]);

            throw $exception;
        }

        $this->debugStep($request, $scope, 'OTP record created', [
            'tenant_id' => $tenantId,
            'otp_id' => $otp->id,
            'phone_hash' => $phoneHash,
        ]);

        try {
            $this->smsGateways->sendSystemOtp($phoneNormalized, $code);
        } catch (Throwable $exception) {
            $this->debugStep($request, $scope, 'OTP SMS sending failed', [
                'tenant_id' => $tenantId,
                'otp_id' => $otp->id,
                'phone_hash' => $phoneHash,
                'exception' => $exception::class,
            ]);

            throw $exception;
        }

        $this->debugStep($request, $scope, 'OTP SMS sent', [
            'tenant_id' => $tenantId,
            'otp_id' => $otp->id,
            'phone_hash' => $phoneHash,
        ]);

        return $otp;
    }

    /**
     * Return the last debug SMS generated by the SMS gateway.
     */
    public function lastDebugSms(): ?string
    {
        return $this->smsGateways->lastDebugSms();
    }

    /**
     * Verify an OTP and create or update the verified lead.
     */
    public function verifyCode(string $phone, string $code, int $tenantId, ?Request $request = null): Lead
    {
        $scope = 'public.otp.service.verify_code';

        $phoneNormalized = $this->normalizePhone($phone);
        $codeNormalized = NumberNormalizer::toLatinDigits($code);
        $phoneHash = hash('sha256', $phoneNormalized);

        $this->debugStep($request, $scope, 'Request received', [
            'tenant_id' => $tenantId,
            'phone_hash' => $phoneHash,
            'code_length' => strlen($codeNormalized),
        ]);

        $otp = OtpCode::query()
            ->where('tenant_id', '=', $tenantId)
            ->where('phone_normalized', '=', $phoneNormalized)
            ->where('purpose', '=', 'lead_login')
            ->whereNull('verified_at')
            ->where('expires_at', '>=', Carbon::now())
            ->orderByDesc('created_at')
            ->first();

        $this->debugStep($request, $scope, 'Active OTP lookup completed', [
            'tenant_id' => $tenantId,
            'phone_hash' => $phoneHash,
            'otp_found' => $otp !== null,
            'otp_id' => $otp?->id,
        ]);

        if (! $otp) {
            $this->debugStep($request, $scope, 'Active OTP not found', [
                'tenant_id' => $tenantId,
                'phone_hash' => $phoneHash,
            ]);

            abort(Response::HTTP_UNPROCESSABLE_ENTITY, __('auth.invalid_lead_otp'));
        }

        if ($otp->attempts >= config('hairvision.otp.max_attempts')) {
            $this->debugStep($request, $scope, 'OTP max attempts reached', [
                'tenant_id' => $tenantId,
                'otp_id' => $otp->id,
                'attempts' => $otp->attempts,
                'max_attempts' => config('hairvision.otp.max_attempts'),
            ]);

            abort(Response::HTTP_UNPROCESSABLE_ENTITY, __('auth.too_many_otp_attempts'));
        }

        if (! Hash::check($codeNormalized, $otp->code_hash)) {
            $newAttempts = $otp->attempts + 1;

            $otp->increment('attempts');

            $this->debugStep($request, $scope, 'OTP code mismatch', [
                'tenant_id' => $tenantId,
                'otp_id' => $otp->id,
                'attempts' => $newAttempts,
                'max_attempts' => config('hairvision.otp.max_attempts'),
            ]);

            if ($newAttempts >= config('hairvision.otp.max_attempts')) {
                $otp->update(['verified_at' => Carbon::now()]);

                $this->debugStep($request, $scope, 'OTP locked after max failed attempts', [
                    'tenant_id' => $tenantId,
                    'otp_id' => $otp->id,
                    'attempts' => $newAttempts,
                ]);
            }

            abort(Response::HTTP_UNPROCESSABLE_ENTITY, __('auth.invalid_lead_otp'));
        }

        $otp->update(['verified_at' => Carbon::now()]);

        $this->debugStep($request, $scope, 'OTP marked as verified', [
            'tenant_id' => $tenantId,
            'otp_id' => $otp->id,
        ]);

        $lead = Lead::updateOrCreate(
            ['tenant_id' => $tenantId, 'phone_normalized' => $phoneNormalized],
            [
                'tenant_id' => $tenantId,
                'phone' => $phoneNormalized,
                'phone_normalized' => $phoneNormalized,
                'phone_verified_at' => Carbon::now(),
                'status' => 'verified',
            ]
        );

        $this->debugStep($request, $scope, 'Lead upserted', [
            'tenant_id' => $tenantId,
            'lead_id' => $lead->id,
            'lead_uuid' => $lead->uuid,
            'phone_hash' => $phoneHash,
        ]);

        return $lead;
    }

    /**
     * Normalize a phone number to Latin digits.
     */
    private function normalizePhone(string $phone): string
    {
        return NumberNormalizer::digitsOnly($phone);
    }

    /**
     * Write a debug step when a request is available.
     *
     * @param  array<string, mixed>  $context
     */
    private function debugStep(?Request $request, string $scope, string $message, array $context = []): void
    {
        if (! $request) {
            return;
        }

        DebugStepLogger::step($request, $scope, $message, $context);
    }
}